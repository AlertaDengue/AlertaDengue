  exit 1
}
mkdir -p "$OUTPUT_ROOT"
OUTPUT_ROOT="$(realpath "$OUTPUT_ROOT")"

tmp_dir="$(mktemp -d)"
declare -a DBS_TO_DROP=()

cleanup() {
  local db
  for db in "${DBS_TO_DROP[@]}"; do
    dropdb --if-exists "$db" >/dev/null 2>&1 || true
  done
  rm -rf "$tmp_dir"
}
trap cleanup EXIT

psql_db() {
  local db="$1"
  shift
  PGDATABASE="$db" psql -X -v ON_ERROR_STOP=1 "$@"
}

add_db() {
  DBS_TO_DROP+=("$1")
}

make_db() {
  local db="$1"
  dropdb --if-exists "$db" >/dev/null 2>&1 || true
  createdb -T template0 "$db"
  add_db "$db"
}

assert_archive_count() {
  local db="$1"
  local expected="$2"
  local got
  got="$(PGDATABASE="$db" psql -X -At -v ON_ERROR_STOP=1 -c "SELECT count(*) FROM pg_namespace WHERE nspname ~ '^archive_'")"
  [[ "$got" == "$expected" ]] || {
    printf 'archive schema count mismatch for %s: expected %s got %s\n' "$db" "$expected" "$got" >&2
    exit 1
  }
}

