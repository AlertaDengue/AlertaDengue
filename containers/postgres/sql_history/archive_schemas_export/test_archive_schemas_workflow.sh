require_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    printf 'missing required command: %s\n' "$1" >&2
    exit 1
  }
}

for cmd in awk cp createdb date dropdb grep mktemp psql realpath rm sha256sum sleep; do
  require_cmd "$cmd"
