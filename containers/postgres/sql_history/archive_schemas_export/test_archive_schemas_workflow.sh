parse_key() {
  local file="$1"
  local key="$2"
  awk -F= -v key="$key" '$1 == key {print $2}' "$file"
}

workflow_export() {
  local db="$1"
  local out="$2"
  PGDATABASE="$db" ARCHIVE_EXPORT_ROOT="$OUTPUT_ROOT" "$WORKFLOW" export --output-root "$OUTPUT_ROOT" > "$out"
}

workflow_verify() {
  local db="$1"
  local package="$2"
  local out="$3"
  PGDATABASE="$db" "$WORKFLOW" verify --package "$package" > "$out"
}

workflow_remove() {
  local db="$1"
  local package="$2"
  local out="$3"
  PGDATABASE="$db" "$WORKFLOW" remove --package "$package" --confirm-database "$db" --confirm-remove REMOVE_NINE_ARCHIVE_SCHEMAS > "$out"
}

expect_fail() {
  local label="$1"
  shift
  if "$@" > "${tmp_dir}/${label}.out" 2> "${tmp_dir}/${label}.err"; then
    printf 'expected failure but command succeeded: %s\n' "$label" >&2
    exit 1
  fi
}

copy_package() {
  local source="$1"
  local target="$2"
  rm -rf "$target"
  cp -a "$source" "$target"
}

prepare_verified_package() {
  local db="$1"
  local tag="$2"
  local export_out="${tmp_dir}/${tag}_export.out"
  local verify_out="${tmp_dir}/${tag}_verify.out"
  workflow_export "$db" "$export_out"
  local package
  package="$(parse_key "$export_out" ARCHIVE_PACKAGE_PATH)"
  workflow_verify "$db" "$package" "$verify_out"
  printf '%s\n' "$package"
}

